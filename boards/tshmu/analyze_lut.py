def get_temp_fast(voltage):
    if voltage >= 3.3: return lut[64]
    if voltage <= 0.0: return lut[0]
    
    f_index = (voltage / 3.3) * 64.0
    idx = int(f_index)
    rem = f_index - idx
    
    if idx >= 64: return lut[64]
    
    t_low = lut[idx]
    t_high = lut[idx+1]
    
    return t_low + (rem * (t_high - t_low))

